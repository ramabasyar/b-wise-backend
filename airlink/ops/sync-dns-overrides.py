#!/usr/bin/env python3
"""Generate exact-name DNS overrides; leave every other public name upstream."""
import os
import re
import subprocess
import tempfile

import psycopg2

TARGET = "/etc/dnsmasq.d/airlink-records.conf"
NAME = re.compile(r"^[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?$", re.I)


def main():
    with psycopg2.connect(os.environ["DNS_LOG_DSN"]) as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT DISTINCT lower(name) FROM records WHERE NOT disabled AND type NOT IN ('SOA','NS') ORDER BY 1")
            names = [row[0].rstrip(".") for row in cur.fetchall()]
    lines = ["# Generated by Airlink. Do not edit manually.\n"]
    for name in names:
        if not NAME.fullmatch(name) or ".." in name or len(name) > 253:
            raise ValueError(f"invalid DNS name: {name}")
        lines.append(f"server=/{name}/127.0.0.1#5300\n")
    directory = os.path.dirname(TARGET)
    fd, temp = tempfile.mkstemp(prefix="airlink-records-", suffix=".conf", dir=directory)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.writelines(lines)
        # Test complete configuration with generated overrides in place, rollback on failure.
        previous = open(TARGET, "rb").read() if os.path.exists(TARGET) else None
        os.replace(temp, TARGET)
        try:
            subprocess.run(["dnsmasq", "--test"], check=True)
            subprocess.run(["systemctl", "restart", "dnsmasq"], check=True)
        except Exception:
            if previous is None:
                os.unlink(TARGET)
            else:
                with open(TARGET, "wb") as handle:
                    handle.write(previous)
            subprocess.run(["systemctl", "restart", "dnsmasq"], check=False)
            raise
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


if __name__ == "__main__":
    main()
